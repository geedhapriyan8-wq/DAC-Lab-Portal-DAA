// ============================================================
// Build the "expected output" for every runnable DAA code cell.
//
//   node tools/build-daa-outputs.mjs [python-exe]
//
// 1. Loads every js/daa/labs/daa-*.js file in a sandbox.
// 2. Collects the code cells marked `run: true`, in lab order.
// 3. Runs each lab's cells in one Python namespace (like a Colab
//    notebook) from daa/datasets/, via tools/run_cells.py.
// 4. Writes js/daa/labs/daa-outputs.js (text output per cell) and
//    daa/img/*.png (any charts the cells draw).
// Re-run this whenever lab code or datasets change.
// ============================================================
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root    = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const labsDir = path.join(root, 'js', 'daa', 'labs');
const python  = process.argv[2] || 'python';

const sandbox = { window: {} };
vm.createContext(sandbox);
for (const f of fs.readdirSync(labsDir).sort()) {
  if (!/^daa-\d{2}-.*\.js$/.test(f)) continue;
  vm.runInContext(fs.readFileSync(path.join(labsDir, f), 'utf8'), sandbox, { filename: f });
}
const labs = sandbox.window.DAA_LAB_DATA || {};

// Same ordering rule as daa-lab-viewer.js: steps in order, code blocks in order.
const jobs = {};
for (const [key, lab] of Object.entries(labs)) {
  const cells = [];
  for (const step of lab.steps) {
    const codes = step.code ? (Array.isArray(step.code) ? step.code : [step.code]) : [];
    for (const c of codes) if (c.run) cells.push({ content: c.content, expectError: !!c.expectError });
  }
  if (cells.length) jobs[key] = cells;
}

const jobFile = path.join(root, 'tools', '.cells.json');
fs.writeFileSync(jobFile, JSON.stringify(jobs));
const out = execFileSync(python, [path.join(root, 'tools', 'run_cells.py'), jobFile, root],
  { maxBuffer: 64 * 1024 * 1024, encoding: 'utf8' });
fs.unlinkSync(jobFile);

const results = JSON.parse(out);
let failures = 0;
for (const [key, cells] of Object.entries(results)) {
  cells.forEach((c, i) => {
    if (c.error) { failures++; console.error(`✗ ${key} cell ${i}: ${c.error.split('\n').slice(-2).join(' ')}`); }
  });
}

const banner = '/* Generated by tools/build-daa-outputs.mjs. Do not edit by hand. */\n';
fs.writeFileSync(path.join(labsDir, 'daa-outputs.js'),
  banner + 'window.DAA_OUTPUTS = ' + JSON.stringify(results, null, 1) + ';\n');
console.log(`Wrote outputs for ${Object.keys(results).length} labs, ${failures} failing cells.`);
process.exit(failures ? 1 : 0);
